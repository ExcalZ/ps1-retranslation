"""The proportional face for vwf_dialogue: tables for the game, and the same renderer in Python.

    python tools/diafont.py            writes PSI_Disasm/ext/vwffont.asm

The face is the series' (tools/vwfmixed.py: the PS IV retranslation's menu face, as PS II and
PS III use it): 8 px tall in one tile row, mixed case. Every glyph is drawn in the cell's rows
0-7 from its top row down, left-aligned; its advance is its ink width plus a 1 px gap (space 3).

Codes (one byte each, as the printer reads them with vwf_dialogue): $20-$5A are ASCII (the
stock's own; $40 and $27 are both the apostrophe), $66-$7F are a-z (the stock printer ended a
message on them; vwf_dialogue only ends on $65), and the codes the stock font drew blank give
the face's other marks by their ASCII: $22 ", $25 %, $26 &, $28 (, $29 ), $2F /, $3A :, $3B ;.
$5B-$65 are the controls and have no glyph.

ext/vwffont.asm: VwfAdvance (96 bytes, codes $20-$7F) and VwfGlyphs (96 x 8 bytes, one byte a
row, bit 7 the leftmost pixel). render() and decode() are used by the harness and linecheck.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import ps1text as T
import vwfmixed as V

SPACE = 3
LINE_PX = 80                 # a dialogue line: 10 tiles (docs/pipeline.md 6, vwf_dialogue)


def code_char():
    """code -> character, for every code that has a glyph (or is the space)."""
    m = {0x20: ' '}
    for c in range(0x21, 0x5B):
        ch = "'" if c == 0x40 else chr(c)
        if ch in V.G:
            m[c] = ch
    for i, c in enumerate(range(0x66, 0x80)):
        m[c] = chr(ord('a') + i)
    return m


CODE_CHAR = code_char()
CHAR_CODE = {}
for _c, _ch in sorted(CODE_CHAR.items()):
    CHAR_CODE.setdefault(_ch, _c)
CHAR_CODE["'"] = 0x40                     # the stock's own apostrophe code


def glyph(ch):
    """(advance, 8 row bytes)."""
    if ch == ' ':
        return SPACE, [0] * 8
    top, rows = V.G[ch]
    out = [0] * 8
    for i, r in enumerate(rows):
        bits = 0
        for x, p in enumerate(r):
            if p == '#':
                bits |= 0x80 >> x
        out[top + i] = bits
    return V.ink(ch) + 1, out


def advance(ch):
    return glyph(ch)[0]


def width(text):
    """Pixels a run of plain characters takes."""
    return sum(advance(ch) for ch in text)


def render(text, px=LINE_PX):
    """Plain characters -> 8 rows of px pixels (lists of 0/1), as the game composes them."""
    rows = [[0] * px for _ in range(8)]
    x = 0
    for ch in text:
        adv, g = glyph(ch)
        for r in range(8):
            for i in range(8):
                if g[r] & (0x80 >> i) and x + i < px:
                    rows[r][x + i] = 1
        x += adv
    return rows


def decode(rows):
    """8 rows of pixels -> the text that renders to them (the longest match first at each pen
    position; trailing blank columns end the line). '0' and 'O' look the same: 'O' is read."""
    px = len(rows[0])
    cands = []
    for ch in CHAR_CODE:
        if ch == '0':
            continue
        adv, g = glyph(ch)
        cands.append((ch, adv, g))
    cands.sort(key=lambda c: -c[1])

    def fits(x, adv, g):
        for r in range(8):
            for i in range(adv):
                bit = 1 if (i < 8 and g[r] & (0x80 >> i)) else 0
                have = rows[r][x + i] if x + i < px else 0
                if bit != have:
                    return False
        return True

    out, x = [], 0
    while x < px:
        if not any(rows[r][c] for r in range(8) for c in range(x, px)):
            break
        for ch, adv, g in cands:
            if ch != ' ' and fits(x, adv, g):
                out.append(ch)
                x += adv
                break
        else:
            if fits(x, SPACE, [0] * 8):
                out.append(' ')
                x += SPACE
            else:
                out.append('~')
                x += 1
    return ''.join(out)


def asm():
    adv, rows = [], []
    for c in range(0x20, 0x80):
        ch = CODE_CHAR.get(c)
        if ch is None:
            adv.append(0)
            rows.append([0] * 8)
        else:
            a, g = glyph(ch)
            adv.append(a)
            rows.append(g)
    lines = ['; Generated by tools/diafont.py from tools/vwfmixed.py - do not edit by hand.',
             '; The series face for vwf_dialogue: advance (ink + 1 px gap; space 3) and 8 row bytes',
             '; for codes $20-$7F (a-z at $66-$7F).',
             'VwfAdvance:']
    for i in range(0, 96, 16):
        lines.append('.db ' + ', '.join('$%02X' % a for a in adv[i:i + 16]))
    lines.append('VwfGlyphs:')
    for i, g in enumerate(rows):
        ch = CODE_CHAR.get(0x20 + i)
        lines.append('.db ' + ', '.join('$%02X' % b for b in g) + '\t; $%02X %s' % (0x20 + i, ch if ch else '-'))
    return '\r\n'.join(lines) + '\r\n'


def main():
    path = os.path.join(T.DISASM, 'ext', 'vwffont.asm')
    text = asm()
    old = T.read(path) if os.path.exists(path) else None
    if old != text:
        open(path, 'wb').write(text.encode('latin-1'))
        print('wrote ext/vwffont.asm')


if __name__ == '__main__':
    main()
