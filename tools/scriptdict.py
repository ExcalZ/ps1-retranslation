"""The dictionary of script_dictionary: 128 words chosen from the script as the build gives it.

    words(texts)   the 128 words (strings) for these texts, from the cache in text/words.asm
                   when the corpus is unchanged, else chosen afresh
    asm(words, h)  text/words.asm: Dialogue_Word_Index_00-7F in the face's codes, $65-ended

The stock dictionary (docs/pipeline.md 3.3) packs the 1987 English: capitals only, so mixed
case gains little from it. Here the corpus is every entry's text in this build (tools/
stockwrap.py: the en, or the stock text as the build lays it out), the plain runs between
controls and inserts, since a word holds neither. Words are chosen greedily: the substring of
2 to 16 characters that saves the most bytes (each use saves its length less one; the word
costs its length plus its end code) is taken, its uses are cut out of the corpus, and the next
is chosen from what is left, 128 times. The encoder (ps1text.encode_us) then packs each run
longest word first. The choice is deterministic; the corpus's SHA-1 in the file's header lets
a build whose text has not changed reuse it.
"""
import hashlib
import heapq
import json
import os
import re
import sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import ps1text as T

PATH = os.path.join(T.DISASM, 'text', 'words.asm')
MAX_LEN = 16
CUT = '\x01'                            # a run cut where a chosen word was


def corpus(texts):
    """The plain runs of the texts (no controls, no inserts), in order."""
    out = []
    for t in texts:
        out += [p for p in T.TAG.split(t)[::2] if p]
    return out


def digest(runs):
    return hashlib.sha1('\n'.join(runs).encode('utf-8')).hexdigest()


def _subs(s):
    n = len(s)
    for i in range(n):
        for L in range(2, MAX_LEN + 1):
            if i + L > n:
                break
            t = s[i:i + L]
            if CUT in t:
                break
            yield t


def _gain(w, n):
    return n * (len(w) - 1) - (len(w) + 1)


def choose(runs, count=128):
    """The words, greedily by bytes saved."""
    runs = list(runs)
    counts = Counter()
    for r in runs:
        counts.update(_subs(r))
    heap = [(-_gain(w, n), w) for w, n in counts.items() if n > 1]
    heapq.heapify(heap)
    words = []
    while len(words) < count and heap:
        g, w = heapq.heappop(heap)
        now = _gain(w, counts[w])
        if now != -g:                   # stale: back in with its gain now
            if counts[w] > 1:
                heapq.heappush(heap, (-now, w))
            continue
        if now <= 0:
            break
        words.append(w)
        for i, r in enumerate(runs):
            if w in r:
                counts.subtract(_subs(r))
                runs[i] = r.replace(w, CUT)
                counts.update(_subs(runs[i]))
    while len(words) < count:            # a tiny corpus: pad with unused filler
        words.append('~' * (len(words) % 3 + 2))
    return words


def cached():
    """(sha1, words) of text/words.asm, or (None, None)."""
    if not os.path.exists(PATH):
        return None, None
    text = T.read(PATH)
    m = re.search(r'(?m)^; corpus sha1 ([0-9a-f]{40})\r?$', text)
    j = re.search(r'(?m)^; words (\[.*\])\r?$', text)
    if not m or not j:
        return None, None
    return m.group(1), json.loads(j.group(1))


def words(texts):
    runs = corpus(texts)
    h = digest(runs)
    old_h, old = cached()
    if old_h == h:
        return h, old
    return h, choose(runs)


def asm(ws, h):
    charset = T.vwf_charset()
    lines = ['; Generated by tools/gentext.py (tools/scriptdict.py) - do not edit by hand.',
             '; script_dictionary: the 128 words for codes $80-$FF, chosen from this build\'s script.',
             '; corpus sha1 %s' % h,
             '; words %s' % json.dumps(ws, ensure_ascii=True)]
    for i, w in enumerate(ws):
        lines.append('Dialogue_Word_Index_%02X:\t; %r' % (i, w))
        lines.append('.db ' + ', '.join('$%02X' % charset[c] for c in w) + ', $65')
    return '\r\n'.join(lines) + '\r\n'
