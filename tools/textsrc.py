"""The text of the source and of the JP ROM, as lists of strings.

Shared by extract_text.py, gentext.py and test_text.py.

US (from the source): the three files gentext.py writes (PSI_Disasm/text/):
  * dialogue.asm: DialogueBlock (the 341 pointers) and the dialogue blocks (kind `dialogue`);
  * cutscenes.asm: the 23 cut-scene strings LABEL_B49B-LABEL_BA54 (kind `cutscene`);
  * messages.asm: the 174 messages from LABEL_B12_B108 (kind `message`).
ps1.asm and sound/sound_driver.asm include them where the stock had them, or ext/banks.asm in
banks 32-34 with relocate_script. A label's bytes are split after each terminator: the first
string takes the label as its id, the others `LABEL.n` (n from 1).
"""
import os
import re

import ps1text as T

FILES = [
    # (file under PSI_Disasm, the kinds it holds, in the order gentext writes them)
    (os.path.join('text', 'dialogue.asm'), ('dialogue',)),
    (os.path.join('text', 'cutscenes.asm'), ('cutscene',)),
    (os.path.join('text', 'messages.asm'), ('message',)),
]
HEADER = '; Generated by tools/gentext.py from work/dialogue.json - do not edit by hand.'

TERM_US = {0x62, 0x63, 0x64} | set(range(0x65, 0x80))


def kind_of(label):
    if label.startswith('Dialogue_Index_'):
        return 'dialogue'
    if label.startswith('LABEL_B12_'):
        return 'message'
    return 'cutscene'


def split_terminated(data, terms):
    out, cur = [], bytearray()
    for b in data:
        cur.append(b)
        if b in terms:
            out.append(bytes(cur))
            cur = bytearray()
    if cur:
        out.append(bytes(cur))
    return out


def us_strings(defs=None):
    """[(id, label, kind, bytes)] in source order."""
    defs = defs or T.defines()
    out = []
    for f, kinds in FILES:
        blocks = []
        for l in T.read(os.path.join(T.DISASM, f)).split('\r\n'):
            m = re.match(r'(\w+):\s*(;.*)?$', l)
            if m:
                if m.group(1) != 'DialogueBlock':
                    blocks.append([m.group(1), bytearray()])
                continue
            if re.match(r'\s*\.dw\s', l):
                continue                         # the DialogueBlock pointers
            b = T.parse_db(l, defs)
            if b is not None:
                blocks[-1][1] += b
            elif l.strip() and not l.strip().startswith(';'):
                raise ValueError('unexpected line in the text region of %s: %r' % (f, l))
        for label, data in blocks:
            for n, part in enumerate(split_terminated(bytes(data), TERM_US)):
                out.append((label if n == 0 else '%s.%d' % (label, n), label, kind_of(label), part))
    return out


# ---------------------------------------------------------------- the JP ROM

JP_TABLE = 0x80B2               # 02:80B2, 341 pointers
JP_BLOCKS_END = 0xAB1F          # dialogue blocks end at 02:AB1E
JP_MESSAGES = (0xAB1F, 0xB8BF)
JP_CUTSCENES = (0xB8BF, 0xBD94)
JP_ITEMS = 0xBD94               # 02:BD94, 65 x 8
JP_PARTY = 0x3326               # 00:3326, 4 x 4
ENEMIES = 0x867F                # 03:867F, 75 x 32 (the same in both ROMs)
TERM_JP = {0x56, 0x57} | set(range(0x58, 0x100))


def jp_blocks(rom):
    """[(addr, bytes)] for the 341 dialogue blocks in id order."""
    base = 2 * 0x4000 - 0x8000
    ptrs = [rom[base + JP_TABLE + 2 * i] | rom[base + JP_TABLE + 2 * i + 1] << 8 for i in range(341)]
    ends = sorted(set(ptrs)) + [JP_BLOCKS_END]
    out = []
    for p in ptrs:
        e = ends[ends.index(p) + 1]
        out.append((p, rom[base + p:base + e]))
    return out


def jp_run(rom, lo, hi):
    """[(addr, bytes)]: the strings of bank 2 lo..hi split after each terminator."""
    base = 2 * 0x4000 - 0x8000
    out, a = [], lo
    for part in split_terminated(rom[base + lo:base + hi], TERM_JP):
        out.append((a, part))
        a += len(part)
    return out
