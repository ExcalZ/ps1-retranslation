"""The highest tile each enemy's and each person's graphics take, for vwf_windows.

    python tools/vwfwin_tops.py        writes PSI_Disasm/ext/vwfwin_tops.asm

Enemies (B03_EnemyData: bank at byte 16, pointer at 17-18) and the people of the interaction
screen (LABEL_B03_9540 -> LABEL_B03_966C: bank at byte 5, pointer at 6-7) are unpacked by
LABEL_3FA to tile $100 up. Their packed size (four planes of run lists) gives the last tile
they fill; vwf_windows lends the tiles above it, up to $19F (battle) or $1A9 (the field), to
window text. The tables hold the low byte of the first free tile (top + 1 - $100). The data is
stock (the translation never changes it), so the file is generated once and committed; checked
against vramaudit's battles of all 74 enemies (2026-10-17).
"""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import ps1text as T


def packed_tiles(rom, bank, ptr):
    o = bank * 0x4000 + ptr - 0x8000
    longest = 0
    for _ in range(4):
        n = 0
        while True:
            r = rom[o]
            o += 1
            if r == 0:
                break
            o += (r & 0x7F) if r & 0x80 else 1
            n += r & 0x7F
        longest = max(longest, n)
    return math.ceil(longest / 8)


def main():
    syms = T.symbols()
    rom = open(os.path.join(T.DISASM, 'ps1original.sms'), 'rb').read()

    def off(label):
        b, a = syms[label]
        return T.rom_offset(b, a)

    e0 = off('B03_EnemyData')
    enemy = [1]                         # 0: no enemy - from $101
    for i in range(1, 128):
        r = rom[e0 + 32 * i:e0 + 32 * i + 32]
        b, p = r[16], r[17] | r[18] << 8
        enemy.append(packed_tiles(rom, b, p) if i < 75 and b and p >= 0x8000 else 0xA0)
    p0, g0 = off('LABEL_B03_9540'), off('LABEL_B03_966C')
    n_people = (off('LABEL_B03_95BC') - p0) // 2
    person = [1]
    for i in range(1, n_people):
        g = rom[p0 + 2 * i + 1]
        ent = rom[g0 + 8 * g:g0 + 8 * g + 8]
        b, p = ent[5], ent[6] | ent[7] << 8
        person.append(packed_tiles(rom, b, p) if b and p >= 0x8000 else 0xA0)
    lines = ['; Generated by tools/vwfwin_tops.py from the stock ROM - do not edit by hand.',
             '; vwf_windows: the first tile above each enemy\'s and person\'s graphics, - $100.',
             'WinEnemyTops:']
    for i in range(0, 128, 16):
        lines.append('.db ' + ', '.join('$%02X' % min(x, 0xA0) for x in enemy[i:i + 16]))
    lines.append('WinPersonTops:')
    for i in range(0, len(person), 16):
        lines.append('.db ' + ', '.join('$%02X' % min(x, 0xAA) for x in person[i:i + 16]))
    lines.append('WinPersonCount = %d' % len(person))
    out = os.path.join(T.DISASM, 'ext', 'vwfwin_tops.asm')
    open(out, 'wb').write(('\r\n'.join(lines) + '\r\n').encode('latin-1'))
    print('wrote %s: %d enemies (highest top $%03X), %d people (highest $%03X)' % (
        os.path.relpath(out, T.ROOT), 74, 0xFF + max(enemy[1:75]), len(person) - 1, 0xFF + max(person[1:])))


if __name__ == '__main__':
    main()
